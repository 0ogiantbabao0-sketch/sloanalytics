import type { DateConditions } from "./calendar";
export type Hall = {
  id: string;
  name: string;
  address: string;
  lat: number;
  lng: number;
  official_url: string | null;
  hours: string | null;
  lottery_time: string | null;
  lottery_place: string | null;
  lottery_method: string | null;
  parking: string | null;
};
export type Machine = { id: string; name: string };
export type Result = {
  hall_id: string;
  machine_id: string;
  date: string;
  total_diff: number;
  units: number;
  positive_units: number | null;
  games: number | null;
  source_id: string;
  updated_at: string;
};
export type Event = {
  id: string;
  hall_id: string;
  date: string;
  name: string;
  type: string;
  performer: string;
  status: string;
};
export type Source = {
  id: string;
  name: string;
  url: string;
  method: string;
  permission: string;
  definition: string;
  reliability: string;
  retrieved_at: string;
};
export type Search = {
  mode: "demo" | "real";
  center: { name: string; lat: number; lng: number };
  radius: number;
  transport: string;
  targetDate: string;
  targetEnd: string;
  days: number;
  from: string;
  to: string;
  conditions: DateConditions;
  rankingMode: "auto" | "machine" | "hall";
  machineIds: string[];
  hallId: string;
  bestOnly: boolean;
  sort: string;
  comparePrevious: boolean;
};
export type Ranking = {
  hall: Hall;
  machine: Machine;
  distance: number;
  installation: number | null;
  score: number | null;
  confidence: number;
  completeness: number;
  days: number;
  avg: number;
  total: number;
  positiveRate: number | null;
  games: number | null;
  baseline: number | null;
  uplift: number | null;
  trend: number | null;
  previousAvg: number | null;
  reasons: string[];
  records: Result[];
  sources: Source[];
  updatedAt: string;
  events: Event[];
};
export type SearchResponse = {
  rankings: Ranking[];
  hallCount: number;
  eligibleCount: number;
  from: string;
  to: string;
  targetHoliday: string | null;
  streak: {
    length: number;
    index: number;
    position: string;
    start: string;
    end: string;
  };
  warning: string | null;
};
